<?php

declare(strict_types=1);

/**
 * Regenerates src/Admin/AdminAssets.php (PHP edition) and
 * go/internal/admin/assets/alpine.js (Go edition) with a pinned, self-hosted copy of
 * Alpine.js and the two plugins the admin UI uses (@alpinejs/ui for x-dialog,
 * @alpinejs/focus for focus trapping).
 *
 * Usage: php scripts/vendor-alpine.php [version]
 *
 * The admin UI must not load script from a CDN: its pages show S3 secrets.
 * The JS is embedded in a PHP class so it survives the single-file release
 * bundle (scripts/build-release.php only inlines PHP sources).
 */

$version = $argv[1] ?? '3.17.5';
if (preg_match('/^\d+\.\d+\.\d+$/', $version) !== 1) {
    fwrite(STDERR, "Invalid version: {$version}\n");
    exit(1);
}

// Plugins first: their CDN builds register on "alpine:init", which the core
// build dispatches when it starts.
$packages = ['@alpinejs/ui', '@alpinejs/focus', 'alpinejs'];
$parts = [];
$hashes = [];
foreach ($packages as $package) {
    $url = 'https://unpkg.com/' . $package . '@' . $version . '/dist/cdn.min.js';
    $js = @file_get_contents($url);
    if (!is_string($js) || $js === '') {
        fwrite(STDERR, "Download failed: {$url}\n");
        exit(1);
    }
    $hashes[] = ' * ' . $package . '@' . $version . ' sha256=' . hash('sha256', $js);
    $parts[] = rtrim($js) . "\n";
}

$bundle = implode(";\n", $parts);
if (str_contains($bundle, 'ALPINE_JS')) {
    fwrite(STDERR, "Bundle contains the nowdoc terminator; pick another one.\n");
    exit(1);
}

$php = "<?php\n\ndeclare(strict_types=1);\n\nnamespace MiniS3\\Admin;\n\n"
    . "/**\n * Self-hosted admin UI scripts. Generated by scripts/vendor-alpine.php; do not edit.\n"
    . implode("\n", $hashes) . "\n */\n"
    . "final class AdminAssets\n{\n"
    . "    public const ALPINE_VERSION = '" . $version . "';\n\n"
    . "    public static function alpinePath(): string\n    {\n"
    . "        return '/_/assets/alpine-' . self::ALPINE_VERSION . '.js';\n    }\n\n"
    . "    public static function alpine(): string\n    {\n"
    . "        return <<<'ALPINE_JS'\n" . $bundle . "ALPINE_JS;\n    }\n}\n";

$target = dirname(__DIR__) . '/src/Admin/AdminAssets.php';
file_put_contents($target, $php);
echo "Wrote {$target} (" . strlen($bundle) . " bytes of JS)\n";

// The Go edition embeds the same bundle and names the version in a constant.
$goDir = dirname(__DIR__) . '/go/internal/admin';
file_put_contents($goDir . '/assets/alpine.js', $bundle);
$goAssets = $goDir . '/admin_assets.go';
$goSource = (string) file_get_contents($goAssets);
$goSource = preg_replace('/const alpineVersion = "[^"]*"/', 'const alpineVersion = "' . $version . '"', $goSource, 1, $count);
if ($count !== 1) {
    fwrite(STDERR, "alpineVersion constant not found in {$goAssets}\n");
    exit(1);
}
file_put_contents($goAssets, $goSource);
echo "Wrote {$goDir}/assets/alpine.js and set alpineVersion in {$goAssets}\n";
