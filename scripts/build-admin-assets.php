<?php

declare(strict_types=1);

/**
 * Regenerates src/Admin/AdminAssets.php from go/internal/admin/assets/admin.js,
 * the admin UI script both editions serve. Run it after editing admin.js and
 * commit both files.
 *
 * Usage: php scripts/build-admin-assets.php
 *
 * The script is embedded in a PHP class so it survives the single-file release
 * bundle (scripts/build-release.php only inlines PHP sources). The URL carries
 * a hash of the file, so browsers can cache it forever. The Go edition
 * computes the same hash from its embedded copy.
 */

$source = dirname(__DIR__) . '/go/internal/admin/assets/admin.js';
$js = (string) file_get_contents($source);
if ($js === '' || !str_ends_with($js, "\n")) {
    fwrite(STDERR, "{$source} must exist and end with a newline.\n");
    exit(1);
}
if (str_contains($js, 'ADMIN_JS')) {
    fwrite(STDERR, "admin.js contains the nowdoc terminator; pick another one.\n");
    exit(1);
}

// A nowdoc drops the newline before its terminator; script() adds it back so
// both editions serve the same bytes.
$php = "<?php\n\ndeclare(strict_types=1);\n\nnamespace MiniS3\\Admin;\n\n"
    . "/**\n * The admin UI script. Generated by scripts/build-admin-assets.php from\n"
    . " * go/internal/admin/assets/admin.js; do not edit.\n */\n"
    . "final class AdminAssets\n{\n"
    . "    public const SCRIPT_HASH = '" . substr(hash('sha256', $js), 0, 12) . "';\n\n"
    . "    public static function scriptPath(): string\n    {\n"
    . "        return '/_/assets/admin-' . self::SCRIPT_HASH . '.js';\n    }\n\n"
    . "    public static function script(): string\n    {\n"
    . "        return <<<'ADMIN_JS'\n" . $js . "ADMIN_JS . \"\\n\";\n    }\n}\n";

$target = dirname(__DIR__) . '/src/Admin/AdminAssets.php';
file_put_contents($target, $php);
echo "Wrote {$target}\n";
